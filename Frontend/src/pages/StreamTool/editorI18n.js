export const EDITOR_TEXTS = defineMessages({ de, en });

/** Texte des Editors in der gewählten Sprache der Website. */
export function useEditorText() {
  const { lang } = useLanguage({ supported: EDITOR_TEXTS.langs });
  return EDITOR_TEXTS.dict(lang);
}

/**
 * Text zu einem Fehler aus streamToolApi.js (err.status, err.code, err.detail). Ohne Antwort: keine Verbindung.
 * Auf Deutsch der Servertext selbst, sonst der Text zum Code — nie ein deutscher Servertext in der englischen Fassung.
 */
export function apiErrorText(t, e) {
  if (e instanceof TypeError || e?.name === 'TypeError') return t.apiErrors.network;
  if (t.lang === 'de' && e?.message) return e.message;
  const entry = e?.code ? t.apiErrors[e.code] : null;
  if (typeof entry === 'function') return entry(e.detail || '');
  if (entry) return entry;
  return e?.status >= 500 ? t.apiErrors.server : t.apiErrors.generic;
}

/** Hinweis nach einem Raid-Probelauf ohne Clip ({ warning, warningCode } der Antwort). */
export function clipWarningText(t, d) {
  if (t.lang === 'de' && d?.warning) return d.warning;
  return t.clipWarnings[d?.warningCode] || t.clipWarnings.clip_missing;
}
