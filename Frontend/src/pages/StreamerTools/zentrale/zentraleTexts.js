/** Wann etwas zuletzt war, als kurzer Text. ts/now in ms; 0 = nie (dann null). */
export function agoText(t, ts, now, lang = "de") {
  if (!ts) return null;
  const diff = Math.max(0, now - ts);
  const min = Math.floor(diff / 60000);
  if (min < 1) return t.ago.now;
  if (min < 60) return t.ago.min(min);
  const h = Math.floor(min / 60);
  if (h < 24) return t.ago.hour(h);
  const d = Math.floor(h / 24);
  if (d < 7) return t.ago.day(d);
  return t.ago.date(new Date(ts).toLocaleDateString(lang === "en" ? "en-US" : "de-DE", { day: "numeric", month: "short" }));
}

