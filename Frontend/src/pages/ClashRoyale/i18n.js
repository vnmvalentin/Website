/** Wörterbuch zu einer Sprache; unbekannte Kürzel fallen auf Deutsch zurück. */
export const dictFor = (lang) => PAGE_I18N[lang] || PAGE_I18N.de;

/**
 * Einen Fehler in Text übersetzen.
 *
 * @param {object} t      Wörterbuch aus dictFor()
 * @param {object} error  { key?, params?, message? } — key/params kommen vom Server oder
 *                        vom Client selbst, message ist der deutsche Satz des Servers.
 *
 * Kennt diese Client-Version den Schlüssel nicht (alter Tab nach einem Deploy, neuer
 * Fehler im Backend), wird die mitgelieferte Server-Meldung gezeigt. Lieber ein deutscher
 * Satz in einer englischen Oberfläche als eine leere Fehlerblase.
 */
export function resolveError(t, error) {
  if (!error) return '';
  const entry = error.key ? t.errors?.[error.key] : null;
  if (typeof entry === 'function') return entry(error.params || {});
  if (typeof entry === 'string') return entry;
  return error.message || '';
}
