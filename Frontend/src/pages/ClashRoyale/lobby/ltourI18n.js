const DICTS = { de: DE, en: EN, es: ES };
export const ltDict = (lang) => DICTS[lang] || DE;

/** Kurzname des Formats für Zusammenfassungen. */
export const formatLabel = (lt, format) => ({
  single: lt.formatSingle, double: lt.formatDouble, roundrobin: lt.formatRoundRobin,
}[format] || format);

/** Läuft in dieser Lobby ein Lobby-Turnier (ausgelost, nicht nur eingeschaltet)? */
export const tournamentRunning = (lobbyData) => !!lobbyData?.ltour && lobbyData.ltour.phase !== 'setup';
