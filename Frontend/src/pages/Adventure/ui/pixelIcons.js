// Kontur: jedes leere Pixel, das waagrecht/senkrecht an eine Füllung grenzt, wird dunkel
function outline(rows) {
  const h = rows.length, w = rows[0].length;
  const out = rows.map((r) => r.split(""));
  for (let y = 0; y < h; y++) {
    for (let x = 0; x < w; x++) {
      if (rows[y][x] !== ".") continue;
      const n = [[1, 0], [-1, 0], [0, 1], [0, -1]].some(([dx, dy]) => {
        const c = rows[y + dy]?.[x + dx];
        return c && c !== "." && c !== "k";
      });
      if (n) out[y][x] = "k";
    }
  }
  return out.map((r) => r.join(""));
}

export const PIXEL_ICONS = Object.fromEntries(Object.entries(RAW).map(([id, rows]) => [id, outline(rows)]));
