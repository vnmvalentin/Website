export const GIVEAWAY_TEXTS = defineMessages({ de, en });

/** Text zu einem Fehler der Schnittstelle (giveawayApi.js wirft Fehler mit code). */
export function errorText(t, e) {
  if (e instanceof TypeError) return t.errors.network;
  return (e && e.code && t.errors[e.code]) || t.errors.generic;
}

/** Text zu einem Grund aus der Prüfung. */
export function grundText(t, e) {
  const g = t.grund[e.grund];
  return typeof g === "function" ? g(e.wert || 0, e.noetig || 0) : g || "";
}
