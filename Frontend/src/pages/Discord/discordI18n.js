/** Texte in der Sprache der Website (Deutsch oder Englisch). */
export function useDiscordText() {
    const { lang } = useLanguage({ supported: DISCORD_TEXTS.langs });
    return DISCORD_TEXTS.dict(lang);
}

/**
 * Text zu einer Fehlerantwort des Servers ({ error, code }). Auf Deutsch der Servertext selbst (er ist oft genauer),
 * sonst der Text zum Code — nie ein deutscher Servertext in der englischen Fassung.
 */
export function serverErrorText(t, data, fallback = t.errors.generic) {
    if (t.lang === 'de' && data?.error) return data.error;
    return (data?.code && t.errors[data.code]) || fallback;
}

/** Ob eine Statuszeile ein Fehler ist (für die Farbe). Alle Fehlertexte beginnen mit „Fehler“ bzw. „Error“. */
export function isErrorStatus(status) {
    return /^(Fehler|Netzwerkfehler|Error)/.test(String(status || ''));
}
