export const BINGO_TEXTS = defineMessages({ de, en });

/**
 * Fehlertext zu einem Fehler aus bingoApi.js. Bekannte Codes werden übersetzt; ohne Code zeigt Deutsch den Text des
 * Servers (wie bisher), Englisch eine allgemeine Meldung statt eines deutschen Satzes. Ohne Antwort vom Server
 * (Netz weg, Server aus) steht statt „Failed to fetch“ die Meldung „nicht erreichbar“.
 */
export function bingoErrorText(err, lang) {
  const t = BINGO_TEXTS.dict(lang);
  if (err?.code && t.errors[err.code]) return t.errors[err.code];
  if (!err?.status) return t.errors.server;
  if (err.status === 401) return t.errors.login;
  if (err?.status >= 500) return t.errors.server;
  if (lang === "de" && err?.message) return err.message;
  return t.errors.generic;
}
